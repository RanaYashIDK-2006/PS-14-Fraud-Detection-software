# ───────────────────────────────────────────────────────── dataset preparation
def generate_dataset(rows: int, seed: int, noise: float, out_dir: Path) -> Path:
    """Generate the synthetic corpus with the repository's own generator."""
    out_dir.mkdir(parents=True, exist_ok=True)
    target = out_dir / DATASET_NAME
    cmd = [sys.executable, str(GENERATOR), "--n-transactions", str(rows),
           "--seed", str(seed), "--noise", str(noise), "--causal",
           "--outdir", str(out_dir)]
    env = {**os.environ, "PYTHONIOENCODING": "utf-8"}
    proc = subprocess.run(cmd, cwd=str(BACKEND), capture_output=True,
                          text=True, env=env, timeout=1800)
    if proc.returncode != 0 or not target.exists():
        raise RuntimeError(f"dataset generation failed: {proc.stderr[-500:]}")
    generate_dataset.last_request = rows  # noqa: B010 - documented side channel
    return target


def select_rows(csv_path: Path, rows: int, seed: int, out_path: Path):
    """Reproducible selection of exactly `rows` rows (documented seed).

    Returns (frame, selection_meta). Uses pandas: a seeded sample without
    replacement when the corpus is larger than the target, otherwise the
    whole corpus (flagged in the metadata so the report can say so).
    """
    import pandas as pd
    df = pd.read_csv(csv_path)
    total_available = len(df)
    if total_available >= rows:
        selected = df.sample(n=rows, random_state=seed).reset_index(drop=True)
        method = f"pandas.sample(n={rows}, random_state={seed}) without replacement"
    else:
        selected = df.reset_index(drop=True)
        method = (f"all {total_available} generated rows (corpus smaller than the "
                  f"requested {rows})")
    out_path.parent.mkdir(parents=True, exist_ok=True)
    selected.to_csv(out_path, index=False)
    meta = {
        "source_csv": str(csv_path),
        "rows_available": int(total_available),
        "rows_selected": int(len(selected)),
        "selection_method": method,
        "seed": int(seed),
    }
    return selected, meta


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def artifacts_fingerprint() -> str:
    """Stable fingerprint of the core model artifacts this run scored with."""
    names = ["scaler.joblib", "imputer.joblib", "calibrator.joblib",
             "random_forest.joblib", "xgboost_model.joblib", "logistic_regression.joblib"]
    digest = hashlib.sha256()
    present = []
    for name in names:
        path = ARTIFACTS_DIR / name
        if path.exists():
            digest.update(name.encode())
            digest.update(sha256_file(path).encode())
            present.append(name)
    return f"sha256:{digest.hexdigest()[:32]} ({','.join(present) or 'none'})"


def validate_dataset(df, rows_expected: int) -> dict:
    """Schema / value / identifier validation. Returns a validation record."""
    import numpy as np
    problems: list[str] = []
    missing_features = [f for f in ML_FEATURES if f not in df.columns]
    if missing_features:
        problems.append(f"missing feature columns: {missing_features[:8]}")
    usable = df
    invalid_rows = 0
    if not missing_features:
        matrix = df[ML_FEATURES]
        nan_counts = matrix.isna().sum()
        rows_with_nan = int(matrix.isna().any(axis=1).sum())
        non_numeric = [c for c in ML_FEATURES if not np.issubdtype(matrix[c].dtype, np.number)]
        if non_numeric:
            problems.append(f"non-numeric feature columns: {non_numeric[:8]}")
        # Rows with missing features are dropped (counted as skipped), the
        # same 0-imputation the offline pipeline applies is NOT silently
        # applied here: a skipped row is visible in the report.
        usable = df.dropna(subset=ML_FEATURES)
        invalid_rows = len(df) - len(usable)
    else:
        nan_counts = None
        rows_with_nan = 0
    dup_event_ids = int(df["event_id"].duplicated().sum()) if "event_id" in df.columns else None
    has_labels = LABEL_COLUMN in df.columns
    n_fraud = int(df[LABEL_COLUMN].sum()) if has_labels else None
    return {
        "rows_in_file": int(len(df)),
        "rows_expected": int(rows_expected),
        "rows_usable": int(len(usable)),
        "rows_skipped_invalid": int(invalid_rows),
        "rows_with_missing_features": int(rows_with_nan),
        "missing_feature_columns": missing_features,
        "nan_counts_by_feature": ({k: int(v) for k, v in nan_counts.items() if v}
                                  if nan_counts is not None else None),
        "duplicate_event_ids": dup_event_ids,
        "labels_present": bool(has_labels),
        "synthetic_fraud_rows": n_fraud,
        "schema_version": SCHEMA_VERSION,
        "valid": not problems and invalid_rows == 0 and not missing_features,
        "problems": problems,
    }, usable


# ───────────────────────────────────────────────────────────── metric helpers
def binary_metrics(y_true, y_pred_flagged) -> dict:
    """Confusion matrix + precision/recall/F1 by hand (fixture-verifiable)."""
    y_true = [int(v) for v in y_true]
    y_pred_flagged = [int(v) for v in y_pred_flagged]
    if len(y_true) != len(y_pred_flagged):
        raise ValueError("y_true and y_pred_flagged must have equal length")
    tp = sum(1 for t, p in zip(y_true, y_pred_flagged) if t == 1 and p == 1)
    fp = sum(1 for t, p in zip(y_true, y_pred_flagged) if t == 0 and p == 1)
    tn = sum(1 for t, p in zip(y_true, y_pred_flagged) if t == 0 and p == 0)
    fn = sum(1 for t, p in zip(y_true, y_pred_flagged) if t == 1 and p == 0)
    precision = tp / (tp + fp) if (tp + fp) else None
    recall = tp / (tp + fn) if (tp + fn) else None
    if precision is not None and recall is not None and (precision + recall):
        f1 = 2 * precision * recall / (precision + recall)
    else:
        f1 = None
    return {"tp": tp, "fp": fp, "tn": tn, "fn": fn,
            "precision": precision, "recall": recall, "f1": f1}


def ranking_metrics(y_true, scores) -> dict | None:
    """ROC-AUC / PR-AUC via sklearn when available, else unavailable."""
    try:
        from sklearn.metrics import average_precision_score, roc_auc_score
    except Exception:  # noqa: BLE001
        return {"available": False,
                "reason": "scikit-learn is not installed in this environment"}
    y_true = [int(v) for v in y_true]
    if len(set(y_true)) < 2:
        return {"available": False,
                "reason": "only one label class is present in this run"}
    return {"available": True,
            "roc_auc": float(roc_auc_score(y_true, scores)),
            "pr_auc": float(average_precision_score(y_true, scores))}


# ────────────────────────────────────────────────────────────────── execution
def _progress(out_run_dir: Path, payload: dict) -> None:
    payload = {"updated_at": datetime.now(timezone.utc).isoformat(), **payload}
    tmp = out_run_dir / "progress.json.tmp"
    tmp.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    tmp.replace(out_run_dir / "progress.json")


def execute_offline(df, chunk_size: int, progress_cb=None) -> tuple[list[dict], dict]:
    """Score every row with the real offline engine and the live policy.

    Uses FusionEngine (the repository's PS-14 evaluation engine, same
    artifacts the certified evaluation uses), RulesEngine, velocity limits and
    the Risk Engine's own `_evaluate_decision` — imported, never re-implemented.
    """
    import yaml
    from src.risk_engine import main as risk_main
    from src.risk_engine.fusion import FusionEngine
    from src.risk_engine.rules_engine import RulesEngine

    cfg = yaml.safe_load(RULES_PATH.read_text(encoding="utf-8"))
    risk_main.velocity_limits_cfg = cfg.get("velocity_limits")
    risk_main.severity_floor = int(cfg.get("severity_floor", 80))
    fusion = FusionEngine(ARTIFACTS_DIR)
    risk_main.fusion = fusion
    rules = RulesEngine(cfg["rules"], severity_scale=float(cfg.get("severity_scale", 1.0)))

    engine_meta = {
        "engine_class": type(fusion).__name__,
        "engine_version": getattr(fusion, "model_version", None) or "unknown",
        "artifacts_dir": str(ARTIFACTS_DIR),
        "artifacts_fingerprint": artifacts_fingerprint(),
        "locked_threshold": float(getattr(fusion, "locked_threshold", 0.0) or 0.0),
    }

    import numpy as np

    results: list[dict] = []
    t0 = time.time()
    n = len(df)
    for start in range(0, n, chunk_size):
        chunk = df.iloc[start:start + chunk_size]
        feature_dicts = chunk[ML_FEATURES].to_dict(orient="records")
        # Batched inference on the engine's own models (the AGENTS note: never
        # call per-row predict in an offline loop). `predict_many` is the
        # calibrated fused score; in v3 mode predict_combined returns the same
        # value as the weighted score, so ml_weighted == ml_score here.
        ml_scores = np.asarray(fusion.predict_many(feature_dicts), dtype=float)
        # Uncertainty is the variance/disagreement across the engine's member
        # models — computed batched from the same models `components()` uses,
        # so the policy sees the same inputs it would get per row.
        X = np.array([[fd[f] for f in ML_FEATURES] for fd in feature_dicts], dtype=float)
        Xs = fusion._prepare(X)
        member = np.column_stack([
            fusion.models[name].predict_proba(Xs)[:, 1]
            for name in ("logistic_regression", "random_forest", "xgboost")
        ])
        variances = member.var(axis=1)
        disagreements = member.max(axis=1) - member.min(axis=1)
        for idx, fd in enumerate(feature_dicts):
            ml_score = float(ml_scores[idx])
            uncertainty = {
                "model_variance": round(float(variances[idx]), 6),
                "model_disagreement": round(float(disagreements[idx]), 6),
            }
            rule = rules.evaluate(fd)
            dec = risk_main._evaluate_decision(
                fd, ml_score, ml_score, uncertainty,
                False, False, rule)
            results.append({
                "decision": dec["decision"],
                "risk_band": dec["band"],
                "risk_score": dec["score"],
                "ml_score": round(float(ml_score), 6),
                "rule_score": round(float(rule["score"]), 6),
                "reason_codes": dec["reason_codes"],
                "fired_rules": rule["fired_rules"],
                "degraded": False,
                "domain_compatible": dec["domain_compatible"],
            })
        if progress_cb:
            progress_cb(min(start + chunk_size, n), n)
    elapsed = time.time() - t0
    return results, {"engine": engine_meta, "elapsed_s": round(elapsed, 3),
                     "throughput_rows_per_s": round(n / elapsed, 1) if elapsed else None}


def execute_live(df, chunk_size: int, service_url: str, token: str,
                 progress_cb=None, max_retries: int = 2) -> tuple[list[dict], dict]:
    """Score every row through the running Risk Engine's /internal/evaluate-batch."""
    import urllib.error
    import urllib.request

    results: list[dict] = []
    n = len(df)
    failed_rows = 0
    chunk_errors: list[str] = []
    t0 = time.time()
    for start in range(0, n, chunk_size):
        chunk = df.iloc[start:start + chunk_size]
        payload_rows = []
        for _, row in chunk.iterrows():
            payload_rows.append({
                "event_id": str(row["event_id"]),
                "fraud_id": str(row["fraud_id"]),
                "features": {f: float(row[f]) for f in ML_FEATURES},
            })
        body = json.dumps(payload_rows).encode("utf-8")
        attempt = 0
        while True:
            req = urllib.request.Request(
                f"{service_url.rstrip('/')}/internal/evaluate-batch", data=body,
                headers={"Content-Type": "application/json",
                         "X-Internal-Token": token})
            try:
                with urllib.request.urlopen(req, timeout=120) as resp:
                    out = json.load(resp)
                break
            except (urllib.error.URLError, urllib.error.HTTPError, TimeoutError, OSError) as exc:
                attempt += 1
                if attempt > max_retries:
                    chunk_errors.append(f"rows {start}:{start + chunk_size} failed: {exc}")
                    failed_rows += len(payload_rows)
                    out = None
                    break
                time.sleep(min(2.0 * attempt, 6.0))
        if out is not None:
            for r in out.get("results", []):
                results.append({
                    "decision": r.get("decision"),
                    "risk_band": r.get("risk_band"),
                    "risk_score": r.get("risk_score"),
                    "ml_score": r.get("ml_score"),
                    "rule_score": r.get("rule_score"),
                    "reason_codes": r.get("reason_codes", []),
                    "fired_rules": r.get("fired_rules", []),
                    "degraded": bool(r.get("degraded")),
                    "domain_compatible": r.get("domain_compatible"),
                })
        if progress_cb:
            progress_cb(min(start + chunk_size, n), n)
    elapsed = time.time() - t0
    return results, {"service_url": service_url, "chunk_size": chunk_size,
                     "failed_rows": failed_rows, "chunk_errors": chunk_errors[:10],
                     "elapsed_s": round(elapsed, 3),
                     "throughput_rows_per_s": round((n - failed_rows) / elapsed, 1) if elapsed else None}


# ─────────────────────────────────────────────────────────────────── reporting
def aggregate(results: list[dict]) -> dict:
    decisions = Counter(r["decision"] for r in results)
    total = len(results)
    risk_scores = [r["risk_score"] for r in results if isinstance(r.get("risk_score"), (int, float))]
    ml_scores = [r["ml_score"] for r in results if isinstance(r.get("ml_score"), (int, float))]
    return {
        "rows_scored": total,
        "decision_counts": dict(decisions),
        "decision_share": {k: round(v / total, 6) for k, v in decisions.items()} if total else {},
        "risk_score": {
            "min": min(risk_scores) if risk_scores else None,
            "max": max(risk_scores) if risk_scores else None,
            "mean": round(sum(risk_scores) / len(risk_scores), 3) if risk_scores else None,
        },
        "ml_score": {
            "min": round(min(ml_scores), 6) if ml_scores else None,
            "max": round(max(ml_scores), 6) if ml_scores else None,
            "mean": round(sum(ml_scores) / len(ml_scores), 6) if ml_scores else None,
        },
        "degraded_rows": sum(1 for r in results if r.get("degraded")),
        "domain_incompatible_rows": sum(1 for r in results if r.get("domain_compatible") is False),
        "top_reason_codes": dict(Counter(
            c for r in results for c in (r.get("reason_codes") or [])).most_common(12)),
    }


def evaluate_metrics(results: list[dict], labels: list[int] | None) -> dict:
    """Metrics only when ground truth exists; every gap carries a reason."""
    if labels is None:
        return {"available": False,
                "reason": "the dataset carries no ground-truth labels"}
    if len(labels) != len(results):
        return {"available": False,
                "reason": f"label/prediction length mismatch ({len(labels)} vs {len(results)})"}
    flagged = [0 if r["decision"] == "allow" else 1 for r in results]
    bm = binary_metrics(labels, flagged)
    ml_scores = [r.get("ml_score") for r in results]
    has_ml = all(isinstance(v, (int, float)) for v in ml_scores) and len(set(ml_scores)) > 1
    rank = (ranking_metrics(labels, ml_scores) if has_ml else
            {"available": False, "reason": "model scores are constant or absent in this run"})
    per_decision = {}
    for r, lab in zip(results, labels):
        bucket = per_decision.setdefault(r["decision"], {"rows": 0, "synthetic_fraud_rows": 0})
        bucket["rows"] += 1
        bucket["synthetic_fraud_rows"] += int(lab)
    for bucket in per_decision.values():
        bucket["synthetic_fraud_rate"] = round(
            bucket["synthetic_fraud_rows"] / bucket["rows"], 6) if bucket["rows"] else None
    return {
        "available": True,
        "labels": "synthetic ground truth from this repository's generator",
        "positive_class": "synthetic fraud label == 1",
        "flagged_definition": "decision != 'allow' (verify / step_up / decline)",
        "confusion": {"tp": bm["tp"], "fp": bm["fp"], "tn": bm["tn"], "fn": bm["fn"]},
        "precision": bm["precision"], "recall": bm["recall"], "f1": bm["f1"],
        "ranking": rank,
        "per_decision": per_decision,
        "circularity_note": (
            "Labels come from the generator's archetype injection, NOT from the "
            "rules being evaluated, so this is not a rules-vs-itself circular "
            "evaluation. It is still synthetic-data evidence only."),
    }


def git_sha() -> str:
    try:
        out = subprocess.run(["git", "rev-parse", "HEAD"], cwd=str(ROOT),
                             capture_output=True, text=True, timeout=30)
        return out.stdout.strip() if out.returncode == 0 else "unknown"
    except Exception:  # noqa: BLE001
        return "unknown"


def new_report_id() -> str:
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    return f"RPT-{stamp}-{uuid.uuid4().hex[:6]}"


def run_batch(mode: str, rows: int, seed: int, noise: float, out_dir: Path,
              report_id: str | None = None, chunk_size: int = 1000,
              service_url: str = "http://127.0.0.1:8003",
              token: str | None = None, offline_chunk: int = 5000,
              progress_cb=None, generate_if_missing: bool = True) -> dict:
    """Full demo run: dataset -> validation -> execution -> metrics -> report."""
    started = datetime.now(timezone.utc)
    t_start = time.time()
    report_id = report_id or new_report_id()
    run_dir = out_dir / "runs" / report_id
    run_dir.mkdir(parents=True, exist_ok=True)
    _progress(run_dir, {"state": "preparing_dataset", "report_id": report_id,
                        "processed": 0, "total": rows})
    warnings: list[str] = []

    csv_path = out_dir / DATASET_NAME
    generator_rows = None
    if not csv_path.exists():
        if not generate_if_missing:
            raise FileNotFoundError(f"demo dataset missing: {csv_path}")
        # The generator produces slightly fewer events than requested (it emits
        # whole account histories), so request headroom and then select exactly
        # `rows` — the report records both numbers.
        generator_rows = max(rows, int(rows * 1.2) + 1)
        generate_dataset(generator_rows, seed, noise, out_dir)

    summary_path = out_dir / SUMMARY_NAME
    generation_summary = {}
    if summary_path.exists():
        try:
            generation_summary = json.loads(summary_path.read_text(encoding="utf-8"))
        except Exception:  # noqa: BLE001
            warnings.append("generation summary unreadable; dataset provenance is partial")

    selected_path = run_dir / "dataset_selected.csv"
    df, selection = select_rows(csv_path, rows, seed, selected_path)

    _progress(run_dir, {"state": "validating", "report_id": report_id,
                        "processed": 0, "total": rows})
    validation, usable = validate_dataset(df, rows)
    if validation["rows_skipped_invalid"]:
        warnings.append(f"{validation['rows_skipped_invalid']} rows skipped: "
                        "missing/invalid feature values")
    if validation["duplicate_event_ids"]:
        warnings.append(f"{validation['duplicate_event_ids']} duplicate event_id values in the dataset")

    labels = None
    if LABEL_COLUMN in usable.columns:
        labels = [int(v) for v in usable[LABEL_COLUMN].tolist()]

    _progress(run_dir, {"state": "scoring", "report_id": report_id,
                        "processed": 0, "total": int(len(usable))})
    if mode == "offline":
        results, exec_meta = execute_offline(
            usable, offline_chunk,
            progress_cb=(lambda done, total: _progress(
                run_dir, {"state": "scoring", "report_id": report_id,
                          "processed": int(done), "total": int(total)})))
    elif mode == "live":
        token = token or os.environ.get("INTERNAL_TOKEN", "")
        if not token:
            raise RuntimeError("live mode requires INTERNAL_TOKEN")
        results, exec_meta = execute_live(
            usable, chunk_size, service_url, token,
            progress_cb=(lambda done, total: _progress(
                run_dir, {"state": "scoring", "report_id": report_id,
                          "processed": int(done), "total": int(total)})))
        if exec_meta.get("failed_rows"):
            warnings.append(f"{exec_meta['failed_rows']} rows failed to score against the live service")
    else:
        raise ValueError(f"unknown mode: {mode}")

    _progress(run_dir, {"state": "aggregating", "report_id": report_id,
                        "processed": int(len(usable)), "total": int(len(usable))})
    summary = aggregate(results)
    metrics = evaluate_metrics(results, labels)

    finished = datetime.now(timezone.utc)
    report = {
        "report_id": report_id,
        "state": "completed" if len(results) else "failed",
        "started_at": started.isoformat(),
        "completed_at": finished.isoformat(),
        "elapsed_s": round(time.time() - t_start, 3),
        "execution_mode": mode,
        "execution_mode_label": (
            "offline batch (in-process PS-14 FusionEngine + RulesEngine + "
            "live decision policy)" if mode == "offline" else
            f"service-backed batch (Risk Engine at {service_url})"),
        "dataset": {
            "type": "synthetic",
            "generator": "backend/src/generate_synthetic_data.py (--causal)",
            "generator_params": {"rows_requested": rows, "seed": seed, "noise": noise,
                                 "rows_requested_from_generator": generator_rows},
            "generator_summary": generation_summary or None,
            "selection": selection,
            "sha256": sha256_file(selected_path),
            "schema_version": SCHEMA_VERSION,
            "label_provenance": ("synthetic archetype labels produced by the "
                                 "repository's generator"),
        },
        "validation": validation,
        "execution": exec_meta,
        "summary": summary,
        "metrics": metrics,
        "warnings": warnings,
        "limitations": LIMITATIONS,
        "reproducibility": {
            "git_sha": git_sha(),
            "command": (f"python backend/scripts/demo_batch_runner.py --mode {mode} "
                        f"--rows {rows} --seed {seed} --noise {noise}"),
            "runner": f"python {sys.version.split()[0]}",
        },
    }
    (run_dir / "report.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    _progress(run_dir, {"state": report["state"], "report_id": report_id,
                        "processed": int(len(results)), "total": int(len(usable)),
                        "report_file": str(run_dir / "report.json")})
    return report


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--mode", choices=["offline", "live"], default="offline")
    ap.add_argument("--rows", type=int, default=25_000)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--noise", type=float, default=0.15)
    ap.add_argument("--out-dir", default=str(DEFAULT_OUT_DIR))
    ap.add_argument("--chunk-size", type=int, default=1000,
                    help="live-mode HTTP batch size (the service caps it at 1000)")
    ap.add_argument("--offline-chunk", type=int, default=5000)
    ap.add_argument("--service-url", default="http://127.0.0.1:8003")
    ap.add_argument("--report-id", default=None)
    args = ap.parse_args()

    report = run_batch(
        mode=args.mode, rows=args.rows, seed=args.seed, noise=args.noise,
        out_dir=Path(args.out_dir), report_id=args.report_id,
        chunk_size=args.chunk_size, offline_chunk=args.offline_chunk,
        service_url=args.service_url, token=os.environ.get("INTERNAL_TOKEN"),
        progress_cb=lambda done, total: print(
            f"  scored {done}/{total}", flush=True))
    print(json.dumps({k: report[k] for k in
                      ("report_id", "state", "execution_mode", "elapsed_s",
                       "summary", "metrics")}, indent=2)[:2500])
    return 0 if report["state"] == "completed" else 1


if __name__ == "__main__":
    sys.exit(main())
