#!/usr/bin/env python3
"""PS-14 Phase 20 — 25,000-transaction batch demo runner.

Runs the ACTUAL supported evaluation path over a documented synthetic dataset
and persists one report artifact per run:

  1. prepare  : generate (or reuse) a deterministic synthetic dataset with the
                repository's own generator (src/generate_synthetic_data.py),
                then select exactly `--rows` rows with a documented seed;
  2. validate : schema, missing/invalid values, duplicate identifiers;
  3. execute  : score every row through the real engine —
                  offline : FusionEngine (models/artifacts) + RulesEngine +
                            velocity limits + the live Risk Engine's own
                            `_evaluate_decision` policy (imported, not copied);
                  live   : chunked POST /internal/evaluate-batch against the
                            running Risk Engine on :8003;
  4. aggregate: decision distribution, score/degraded summaries, throughput;
  5. metrics  : ROC-AUC / PR-AUC / confusion / precision / recall / F1 against
                the generator's SYNTHETIC labels (only when labels exist);
  6. persist  : <outdir>/runs/<report_id>/report.json + progress.json.

Nothing here invents a score, decision, reason code or metric: every reported
value comes from the engine or from an explicit computation over its outputs.
Synthetic labels are the generator's own ground truth — they are NOT
real-world fraud validation, and a report says so in its `limitations`.

Usage (repo root):
  PYTHONPATH=backend python backend/scripts/demo_batch_runner.py \
      --mode offline --rows 25000 --seed 42 --out-dir db/demo_batch
"""
